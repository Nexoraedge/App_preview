export function translateSlot(slot: string, isHi: boolean): string {
  if (!isHi || !slot) return slot;
  if (SLOTS[slot]) return SLOTS[slot];
  // Fallback for dynamic slots like "Today, 3:30 PM"
  let res = slot;
  res = res.replace(/Today/g, 'आज');
  res = res.replace(/Tomorrow/g, 'कल');
  res = res.replace(/AM/g, 'सुबह');
  res = res.replace(/PM/g, 'शाम');
  return res;
}

export function translateTiming(timing: string, isHi: boolean): string {
  if (!isHi || !timing) return timing;
  if (TIMINGS[timing]) return TIMINGS[timing];
  let res = timing;
  res = res.replace(/Mon/g, 'सोम');
  res = res.replace(/Tue/g, 'मंगल');
  res = res.replace(/Wed/g, 'बुध');
  res = res.replace(/Thu/g, 'गुरु');
  res = res.replace(/Fri/g, 'शुक्र');
  res = res.replace(/Sat/g, 'शनि');
  res = res.replace(/Sun/g, 'रवि');
  res = res.replace(/AM/g, 'सुबह');
  res = res.replace(/PM/g, 'शाम');
  return res;
}

export function translateLanguageList(langs: string[] | undefined, isHi: boolean): string {
  if (!langs || langs.length === 0) return isHi ? 'अंग्रेजी, हिंदी' : 'English, Hindi';
  if (!isHi) return langs.join(', ');
  return langs.map((l) => LANGUAGE_MAP[l] || l).join(', ');
}
